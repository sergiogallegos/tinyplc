class Atom(str):
    pass


def parse(text):
    stack = [[]]
    for t in re.findall(r'"(?:\\.|[^"\\])*"|[()]|[^\s()]+', text):
        if t == "(":
            n = []
            stack[-1].append(n)
            stack.append(n)
        elif t == ")":
            stack.pop()
        else:
            stack[-1].append(json.loads(t) if t.startswith('"') else Atom(t))
    return stack[0][0]


def dump(n):
    if isinstance(n, list):
        return "(" + " ".join(dump(x) for x in n) + ")"
    return str(n) if isinstance(n, Atom) else json.dumps(n)


def kids(n, key):
    return [x for x in n if isinstance(x, list) and x and x[0] == key]


def child(n, key):
    return kids(n, key)[0]


CACHE = {}


def symbol(lib, name):
    if lib not in CACHE:
        data = parse((K / "symbols" / f"{lib}.kicad_sym").read_text())
        CACHE[lib] = {n[1]: n for n in kids(data, "symbol")}
    raw = copy.deepcopy(CACHE[lib][name])
    ext = kids(raw, "extends")
    if ext:
        base = symbol(lib, ext[0][1])
        old = base[1]
        for sub in kids(base, "symbol"):
            sub[1] = sub[1].replace(old, name, 1)
        overrides = {n[1]: n for n in kids(raw, "property")}
        base = [n for n in base if not (isinstance(n, list) and n and n[0] == "property" and n[1] in overrides)]
        base += list(overrides.values())
        base[1] = name
        raw = base
    return raw


def custom(name, pins, width=10.16):
    # Own symbols, numbered from the manufacturers' pin tables.
    h = max(7.62, math.ceil(len(pins) / 2) * 2.54)
    s = f'(symbol "{name}" (pin_names (offset 0.508)) (in_bom yes) (on_board yes)'
    s += f'(property "Reference" "U" (at 0 {h+2.54} 0) (effects (font (size 1.27 1.27))))'
    s += f'(property "Value" "{name}" (at 0 {-h-2.54} 0) (effects (font (size 1.27 1.27))))'
    s += f'(symbol "{name}_0_1" (rectangle (start {-width} {h}) (end {width} {-h}) (stroke (width 0.254) (type default)) (fill (type background))))'
    s += f'(symbol "{name}_1_1"'
    half = math.ceil(len(pins) / 2)
    for i, (num, label, typ) in enumerate(pins):
        left = i < half
        x = -width-5.08 if left else width+5.08
        y = h-2.54-(i if left else i-half)*2.54
        s += f'(pin {typ} line (at {x} {y} {0 if left else 180}) (length 5.08) (name "{label}" (effects (font (size 1 1)))) (number "{num}" (effects (font (size 1 1)))))'
    return parse(s + "))")


