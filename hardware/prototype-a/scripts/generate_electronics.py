def add(ref, sym, value, fp, nets, xy, group, purpose, mpn, doc, angle=0, sch=None, status="candidate; verify before purchase"):
    if sym not in SYMS:
        if sym.startswith("tinyplc:"):
            s = copy.deepcopy(CUSTOM[sym.split(":")[1]])
        else:
            lib, name = sym.split(":")
            s = symbol(lib, name)
        s[1] = sym
        SYMS[sym] = s
    nets = {str(k): v for k, v in nets.items()}
    pin_numbers = {child(p, "number")[1] for sub in kids(SYMS[sym], "symbol") for p in kids(sub, "pin")}
    if ref == "J13" and "S1" in nets:
        nets["SH"] = nets.pop("S1")
    assert set(nets) <= pin_numbers, (ref, set(nets)-pin_numbers)
    pin_names={child(p,"number")[1]:child(p,"name")[1] for sub in kids(SYMS[sym],"symbol") for p in kids(sub,"pin")}
    PARTS.append(dict(ref=ref, symbol=sym, value=value, footprint=fp, nets=nets, pin_names=pin_names, xy=xy, angle=angle,
                      group=group, purpose=purpose, mpn=mpn, official_document=doc, status=status,
                      uuid=uid(ref), sch=sch))


