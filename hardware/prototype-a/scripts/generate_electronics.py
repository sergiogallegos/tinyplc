    gi = gidx[p["group"]]
    gx,gy = origins[p["group"]]
    x,y = p["sch"] or [gx+(gi%3)*57.15,gy+(gi//3)*38.1]
    if p["ref"]!="U1":
        gidx[p["group"]] += 1
    x,y = round(x/1.27)*1.27,round(y/1.27)*1.27
    p["schematic_xy"]=[x,y]
    s = SYMS[p["symbol"]]
    field_y = y-9
    if p["ref"] in ["U1","U3","J13"]:
        field_y = y-52 if p["ref"]=="U1" else y-27
    props = f'(property "Reference" "{p["ref"]}" (at {x} {field_y} 0) (effects (font (size 1.27 1.27))))'
    props += f'(property "Value" {json.dumps(p["value"])} (at {x} {field_y+2.54} 0) (effects (font (size 1.0 1.0))))'
    for key,value in [("Footprint",p["footprint"]),("Datasheet",p["official_document"]),("MPN",p["mpn"]),("Purpose",p["purpose"]),("Status",p["status"])]:
        props += f'(property "{key}" {json.dumps(value)} (at {x} {y} 0) (effects (font (size 1.27 1.27)) (hide yes)))'
    # Use local labels with explicit short wire stubs; all equal names connect on this sheet.
    for sub in kids(s,"symbol"):
        for pin in kids(sub,"pin"):
            num=child(pin,"number")[1]
            at=child(pin,"at")
            px,py=x+float(at[1]),y-float(at[2])
            net=p["nets"].get(num)
            if net is None:
                schematic.append(f'(no_connect (at {px:.4f} {py:.4f}) (uuid "{uid(p["ref"]+num+"nc")}"))')
                continue
            a=math.radians(float(at[3]))
            ex,ey=round(px-5.08*math.cos(a),4),round(py+5.08*math.sin(a),4)
            schematic.append(f'(wire (pts (xy {px:.4f} {py:.4f}) (xy {ex} {ey})) (stroke (width 0) (type default)) (uuid "{uid(p["ref"]+num+"wire")}"))')
            rot=0 if abs(math.cos(a))>0.1 else 90
            just="right bottom" if float(at[3])==0 else "left bottom"
            schematic.append(f'(label "{net}" (at {ex} {ey} {rot}) (effects (font (size 1 1)) (justify {just})) (uuid "{uid(p["ref"]+num+"label")}"))')
    bom="no" if p["ref"].startswith(("TP","H")) else "yes"
    schematic.append(f'(symbol (lib_id "{p["symbol"]}") (at {x} {y} 0) (unit 1) (in_bom {bom}) (on_board yes) (dnp no) (uuid "{p["uuid"]}") {props} (instances (project "tinyplc-a0" (path "/{SHEET}" (reference "{p["ref"]}") (unit 1)))))')

